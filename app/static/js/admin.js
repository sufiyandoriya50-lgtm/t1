// Reads the CSRF token generated by Flask-JWT-Extended.
function getCsrfToken() {
    const cookie = document.cookie
        .split("; ")
        .find(item => item.startsWith("csrf_access_token="));

    if (!cookie) return "";

    try {
        return decodeURIComponent(
            cookie.substring("csrf_access_token=".length)
        );
    } catch {
        return "";
    }
}


// Sends authenticated requests to the Flask API.
async function apiRequest(url, options = {}) {
    const headers = new Headers(options.headers || {});
    headers.set("Accept", "application/json");

    const method = (options.method || "GET").toUpperCase();

    if (
        options.body &&
        !(options.body instanceof FormData) &&
        !headers.has("Content-Type")
    ) {
        headers.set("Content-Type", "application/json");
    }

    if (["POST", "PUT", "PATCH", "DELETE"].includes(method)) {
        const csrfToken = getCsrfToken();

        if (csrfToken) {
            headers.set("X-CSRF-TOKEN", csrfToken);
        }
    }

    const response = await fetch(url, {
        ...options,
        method,
        headers,
        credentials: "same-origin"
    });

    let result = {};

    try {
        result = await response.json();
    } catch {
        result = {};
    }

    if (response.status === 401 || response.status === 403) {
        if (url !== API.logout) {
            window.location.assign("/admin/login");
        }

        throw new Error(
            result.message || "Administrator authentication failed."
        );
    }

    if (!response.ok) {
        throw new Error(
            result.message || `Request failed (${response.status}).`
        );
    }

    return result;
}


// Displays an error in the dashboard alert.
function showError(message) {
    const element = $("dashboardError");

    element.textContent = message || "An unexpected error occurred.";
    element.classList.remove("d-none");

    $("dashboardSuccess").classList.add("d-none");
}


// Displays a success message.
function showSuccess(message) {
    const element = $("dashboardSuccess");

    element.textContent = message || "Operation completed successfully.";
    element.classList.remove("d-none");

    $("dashboardError").classList.add("d-none");

    window.setTimeout(() => {
        element.classList.add("d-none");
    }, 6000);
}


// Clears global feedback.
function clearFeedback() {
    $("dashboardError").classList.add("d-none");
    $("dashboardSuccess").classList.add("d-none");
}


// Formats dates safely.
function formatDate(value) {
    if (!value) return "Unavailable";

    const date = new Date(value);

    return Number.isNaN(date.getTime())
        ? "Unavailable"
        : date.toLocaleString();
}


// Formats optional numeric values.
function formatNumber(value, suffix = "") {
    if (value === null || value === undefined || value === "") {
        return "Unavailable";
    }

    const number = Number(value);

    return Number.isFinite(number)
        ? `${number}${suffix}`
        : String(value);
}


// Creates a safe table cell.
function createCell(value, className = "") {
    const cell = document.createElement("td");

    cell.textContent =
        value === null || value === undefined || value === ""
            ? "—"
            : String(value);

    if (className) {
        cell.className = className;
    }

    return cell;
}


// Creates a status badge.
function createStatusBadge(status) {
    const badge = document.createElement("span");

    const normalized = String(status || "").toLowerCase();

    const classes = {
        pending: "text-bg-warning",
        verified: "text-bg-success",
        rejected: "text-bg-danger",
        low: "text-bg-success",
        moderate: "text-bg-warning",
        high: "text-bg-danger",
        severe: "text-bg-dark"
    };

    badge.className =
        `badge ${classes[normalized] || "text-bg-secondary"}`;

    badge.textContent = status || "Unknown";

    return badge;
}


// Creates a query string from non-empty values.
function queryString(values) {
    const params = new URLSearchParams();

    Object.entries(values).forEach(([key, value]) => {
        if (
            value !== undefined &&
            value !== null &&
            value !== ""
        ) {
            params.set(key, String(value));
        }
    });

    return params.toString();
}


// Creates a table row for empty or loading states.
function renderTableMessage(body, message, columns, className = "") {
    body.replaceChildren();

    const row = document.createElement("tr");
    const cell = createCell(message, `table-message ${className}`.trim());

    cell.colSpan = columns;

    row.appendChild(cell);
    body.appendChild(row);
}


// Validates coordinates supplied in a form.
function readCoordinates(latitudeId, longitudeId) {
    const latitudeText = $(latitudeId).value.trim();
    const longitudeText = $(longitudeId).value.trim();

    if (!latitudeText || !longitudeText) {
        throw new Error("Enter both latitude and longitude.");
    }

    const latitude = Number(latitudeText);
    const longitude = Number(longitudeText);

    if (
        !Number.isFinite(latitude) ||
        latitude < -90 ||
        latitude > 90 ||
        !Number.isFinite(longitude) ||
        longitude < -180 ||
        longitude > 180
    ) {
        throw new Error("Enter valid latitude and longitude values.");
    }

    return { latitude, longitude };
}


// Validates a positive radius.
function readRadius(elementId) {
    const text = $(elementId).value.trim();
    const radius = Number(text);

    if (!text || !Number.isFinite(radius) || radius <= 0) {
        throw new Error("Enter a valid positive radius.");
    }

    return radius;
}


