// Loads historical flood events with pagination and filters.
async function loadHistoricalEvents() {
    const requestNumber = ++state.historicalRequest;
    const body = $("historicalTableBody");

    renderTableMessage(
        body,
        "Loading historical events...",
        8
    );

    $("historicalSummary").textContent = "Loading events...";

    try {
        const start = $("historicalStart").value;
        const end = $("historicalEnd").value;

        if (start && end && start > end) {
            throw new Error(
                "Historical start date must not be after end date."
            );
        }

        const params = queryString({
            severity: $("historicalSeverity").value,
            start_date: start,
            end_date: end,
            page: state.historicalPage,
            per_page: $("historicalPageSize").value
        });

        const result = await apiRequest(
            `${API.historical}?${params}`
        );

        if (requestNumber !== state.historicalRequest) return;

        if (
            result.status !== "success" ||
            !Array.isArray(result.events)
        ) {
            throw new Error(
                "Invalid historical flood response."
            );
        }

        body.replaceChildren();

        result.events.forEach(event => {
            const row = document.createElement("tr");

            row.appendChild(createCell(event.id));
            row.appendChild(createCell(event.event_name));
            row.appendChild(createCell(formatDate(event.event_date)));

            const severity = document.createElement("td");
            severity.appendChild(
                createStatusBadge(event.severity)
            );

            row.appendChild(severity);

            row.appendChild(
                createCell(
                    event.water_depth_cm == null
                        ? "—"
                        : `${event.water_depth_cm} cm`
                )
            );

            row.appendChild(
                createCell(
                    `${event.latitude}, ${event.longitude}`
                )
            );

            row.appendChild(
                createCell(event.source || "—")
            );

            const action = document.createElement("td");
            const button = document.createElement("button");

            button.type = "button";
            button.className = "btn btn-outline-primary btn-sm";
            button.textContent = "Details";
            button.dataset.historicalId = event.id;

            action.appendChild(button);
            row.appendChild(action);

            body.appendChild(row);
        });

        if (!result.events.length) {
            renderTableMessage(
                body,
                "No historical events found.",
                8
            );
        }

        const total = Number(result.total ?? 0);

        state.historicalPages = Number(result.pages ?? 0);

        $("historicalSummary").textContent =
            `${total} historical event(s) found`;

        $("historicalPaginationInfo").textContent =
            state.historicalPages
                ? `Page ${state.historicalPage} of ${state.historicalPages}`
                : "No pages";

        $("historicalPrevious").disabled =
            state.historicalPage <= 1;

        $("historicalNext").disabled =
            !state.historicalPages ||
            state.historicalPage >= state.historicalPages;

        state.loadedModules.add("historical");

    } catch (error) {
        if (requestNumber !== state.historicalRequest) return;

        renderTableMessage(
            body,
            error.message,
            8,
            "text-danger"
        );

        $("historicalSummary").textContent =
            "Unable to load historical events.";

        $("historicalPaginationInfo").textContent = "";

        $("historicalPrevious").disabled = true;
        $("historicalNext").disabled = true;

        showError(error.message);
    }
}


