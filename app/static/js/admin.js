// Collects and validates report search filters.
function collectReportFilters() {
    const params = new URLSearchParams();

    const search = $("reportSearch").value.trim();
    const status = $("statusFilter").value;
    const start = $("startDateFilter").value;
    const end = $("endDateFilter").value;

    if (search) params.set("search", search);
    if (status) params.set("status", status);

    if (start && end && start > end) {
        throw new Error("Start date must not be after end date.");
    }

    if (start) {
        params.set("start_date", `${start}T00:00:00`);
    }

    if (end) {
        params.set("end_date", `${end}T23:59:59.999999`);
    }

    const latitudeText = $("latitudeFilter").value.trim();
    const longitudeText = $("longitudeFilter").value.trim();
    const radiusText = $("radiusFilter").value.trim();

    const locationValues = [
        latitudeText,
        longitudeText,
        radiusText
    ];

    if (locationValues.some(Boolean)) {
        if (!locationValues.every(Boolean)) {
            throw new Error(
                "Enter latitude, longitude and radius together."
            );
        }

        const latitude = Number(latitudeText);
        const longitude = Number(longitudeText);
        const radius = Number(radiusText);

        if (
            !Number.isFinite(latitude) ||
            latitude < -90 ||
            latitude > 90 ||
            !Number.isFinite(longitude) ||
            longitude < -180 ||
            longitude > 180 ||
            !Number.isFinite(radius) ||
            radius <= 0 ||
            radius > 500
        ) {
            throw new Error(
                "Enter valid coordinates and a radius up to 500 km."
            );
        }

        params.set("latitude", String(latitude));
        params.set("longitude", String(longitude));
        params.set("radius_km", String(radius));
    }

    return params;
}


// Loads the report management table.
async function loadReports() {
    const requestNumber = ++state.reportRequest;
    const body = $("reportTableBody");

    renderTableMessage(body, "Loading reports...", 7);

    $("applyFiltersButton").disabled = true;
    $("pendingQueueButton").disabled = true;

    try {
        const params = collectReportFilters();

        params.set("page", String(state.page));
        params.set("per_page", String(state.perPage));

        const url = state.pendingQueue
            ? `${API.pending}?page=${state.page}&per_page=${state.perPage}`
            : `${API.reports}?${params.toString()}`;

        const result = await apiRequest(url);

        if (requestNumber !== state.reportRequest) return;

        if (
            result.status !== "success" ||
            !Array.isArray(result.reports)
        ) {
            throw new Error("Invalid reports response.");
        }

        state.totalReports = Number(result.total_reports ?? 0);
        state.totalPages = Number(result.total_pages ?? 0);

        renderReportTable(result.reports);

        $("reportResultSummary").textContent =
            `${state.totalReports} report(s) found`;

        $("paginationInfo").textContent = state.totalPages
            ? `Page ${state.page} of ${state.totalPages}`
            : "No pages";

        $("previousPageButton").disabled = state.page <= 1;

        $("nextPageButton").disabled =
            !state.totalPages || state.page >= state.totalPages;

    } catch (error) {
        if (requestNumber !== state.reportRequest) return;

        renderTableMessage(
            body,
            error.message,
            7,
            "text-danger"
        );

        $("reportResultSummary").textContent =
            "Unable to load reports.";

        $("paginationInfo").textContent = "";
        $("previousPageButton").disabled = true;
        $("nextPageButton").disabled = true;

        showError(error.message);

    } finally {
        if (requestNumber === state.reportRequest) {
            $("applyFiltersButton").disabled = false;
            $("pendingQueueButton").disabled = false;
        }
    }
}


