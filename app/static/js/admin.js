// Renders protected report media.
function renderReportMedia(items) {
    const container = $("detailMedia");

    container.replaceChildren();

    if (!Array.isArray(items) || !items.length) {
        const empty = document.createElement("p");

        empty.className = "text-muted";
        empty.textContent = "No photographs are attached.";

        container.appendChild(empty);
        return;
    }

    items.forEach(media => {
        const wrapper = document.createElement("div");
        wrapper.className = "media-item";

        const image = document.createElement("img");

        image.src = media.image_url;
        image.alt = `Flood report ${media.report_id} photograph`;
        image.loading = "lazy";
        image.referrerPolicy = "same-origin";

        image.addEventListener("error", () => {
            image.replaceWith(
                document.createTextNode("Photograph unavailable.")
            );
        }, { once: true });

        const caption = document.createElement("p");

        caption.className = "small text-muted mt-2 mb-0";
        caption.textContent =
            `${media.mime_type || "Image"} · ${formatDate(media.uploaded_at)}`;

        wrapper.append(image, caption);
        container.appendChild(wrapper);
    });
}


// Loads report moderation history.
async function loadModerationHistory() {
    if (!state.currentReportId) return;

    $("historyContent").textContent =
        "Loading moderation history...";

    $("historyError").classList.add("d-none");

    state.historyModal.show();

    try {
        const result = await apiRequest(
            API.history(state.currentReportId)
        );

        if (
            result.status !== "success" ||
            !Array.isArray(result.history)
        ) {
            throw new Error(
                "Invalid moderation history response."
            );
        }

        const container = $("historyContent");
        container.replaceChildren();

        if (!result.history.length) {
            container.textContent =
                "No moderation actions have been recorded.";
            return;
        }

        const table = document.createElement("table");
        table.className = "table align-middle";

        const head = document.createElement("thead");
        const header = document.createElement("tr");

        [
            "Administrator",
            "Previous Status",
            "New Status",
            "Date"
        ].forEach(label => {
            const th = document.createElement("th");
            th.textContent = label;
            header.appendChild(th);
        });

        head.appendChild(header);

        const body = document.createElement("tbody");

        result.history.forEach(record => {
            const row = document.createElement("tr");

            row.appendChild(
                createCell(record.admin_name || "Unavailable")
            );

            row.appendChild(
                createCell(record.previous_status || "—")
            );

            const status = document.createElement("td");
            status.appendChild(
                createStatusBadge(record.new_status)
            );

            row.appendChild(status);
            row.appendChild(
                createCell(formatDate(record.created_at))
            );

            body.appendChild(row);
        });

        table.append(head, body);
        container.appendChild(table);

    } catch (error) {
        $("historyError").textContent = error.message;
        $("historyError").classList.remove("d-none");
    }
}


// Requests confirmation before report moderation.
function requestModerationAction(action) {
    if (!state.currentReportId) return;

    if (!["verify", "reject"].includes(action)) return;

    state.pendingModerationAction = action;

    const verb = action === "verify" ? "verify" : "reject";

    $("moderationConfirmTitle").textContent =
        `${verb.charAt(0).toUpperCase()}${verb.slice(1)} Report`;

    $("moderationConfirmMessage").textContent =
        `Are you sure you want to ${verb} report #${state.currentReportId}?`;

    $("confirmModerationButton").textContent =
        verb.charAt(0).toUpperCase() + verb.slice(1);

    $("confirmModerationButton").className =
        `btn ${action === "verify" ? "btn-success" : "btn-danger"}`;

    state.confirmModal.show();
}


// Performs report moderation.
async function performModerationAction() {
    const action = state.pendingModerationAction;
    const id = state.currentReportId;

    if (!action || !id) return;

    const button = $("confirmModerationButton");

    button.disabled = true;
    button.textContent = "Processing...";

    try {
        const url = action === "verify"
            ? API.verify(id)
            : API.reject(id);

        const result = await apiRequest(url, {
            method: "PATCH"
        });

        state.confirmModal.hide();
        state.detailsModal.hide();

        showSuccess(
            result.message || `Report #${id} updated successfully.`
        );

        await Promise.all([
            loadDashboardStats(),
            loadReports()
        ]);

    } catch (error) {
        showError(error.message);

    } finally {
        button.disabled = false;
        state.pendingModerationAction = null;
        button.textContent = "Confirm";
    }
}


// Resets report filters.
