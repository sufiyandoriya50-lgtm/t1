// Creates a historical flood event.
async function createHistoricalEvent(event) {
    event.preventDefault();

    const button = $("saveHistoricalEventButton");
    const errorBox = $("historicalCreateError");

    errorBox.classList.add("d-none");

    button.disabled = true;
    button.textContent = "Saving...";

    try {
        const latitude = Number($("eventLatitude").value);
        const longitude = Number($("eventLongitude").value);

        const depthText = $("eventDepth").value.trim();
        const depth = depthText === ""
            ? null
            : Number(depthText);

        if (
            !Number.isFinite(latitude) ||
            latitude < -90 ||
            latitude > 90 ||
            !Number.isFinite(longitude) ||
            longitude < -180 ||
            longitude > 180
        ) {
            throw new Error("Enter valid event coordinates.");
        }

        if (
            depth !== null &&
            (!Number.isFinite(depth) || depth < 0)
        ) {
            throw new Error(
                "Water depth must be zero or greater."
            );
        }

        const payload = {
            event_name: $("eventName").value.trim(),
            latitude,
            longitude,
            event_date: $("eventDate").value,
            water_depth_cm: depth,
            severity: $("eventSeverity").value,
            description: $("eventDescription").value.trim(),
            source: $("eventSource").value.trim(),
            source_reference: $("eventReference").value.trim()
        };

        if (
            !payload.event_name ||
            !payload.event_date ||
            !payload.severity
        ) {
            throw new Error(
                "Complete all required event fields."
            );
        }

        const result = await apiRequest(API.historical, {
            method: "POST",
            body: JSON.stringify(payload)
        });

        state.historicalModal.hide();

        $("historicalCreateForm").reset();

        showSuccess(
            result.message || "Historical event created."
        );

        state.historicalPage = 1;

        await loadHistoricalEvents();

    } catch (error) {
        errorBox.textContent = error.message;
        errorBox.classList.remove("d-none");

    } finally {
        button.disabled = false;
        button.textContent = "Save Event";
    }
}


