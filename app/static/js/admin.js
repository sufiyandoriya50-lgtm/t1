// Displays weather values as safe text.
function renderWeatherObject(container, data) {
    container.replaceChildren();

    if (!data || typeof data !== "object") {
        container.textContent =
            "No weather data is available.";
        return;
    }

    const list = document.createElement("dl");
    list.className = "row mb-0";

    const labels = {
        temperature_c: "Temperature",
        rainfall_mm: "Rainfall",
        wind_speed_kmh: "Wind speed",
        weather_code: "Weather code",
        recorded_at: "Recorded at",
        source: "Source",
        latitude: "Latitude",
        longitude: "Longitude"
    };

    const suffixes = {
        temperature_c: " °C",
        rainfall_mm: " mm",
        wind_speed_kmh: " km/h"
    };

    Object.entries(labels).forEach(([key, label]) => {
        if (
            data[key] === undefined ||
            data[key] === null
        ) {
            return;
        }

        const term = document.createElement("dt");
        term.className = "col-5";
        term.textContent = label;

        const value = document.createElement("dd");
        value.className = "col-7";

        value.textContent = key === "recorded_at"
            ? formatDate(data[key])
            : `${data[key]}${suffixes[key] || ""}`;

        list.append(term, value);
    });

    if (!list.children.length) {
        container.textContent =
            "The weather service returned no displayable fields.";
    } else {
        container.appendChild(list);
    }
}


// Retrieves current and latest stored weather for coordinates.
async function loadWeather() {
    const button = $("weatherLoadButton");
    const collectButton = $("weatherCollectButton");

    button.disabled = true;
    collectButton.disabled = true;

    try {
        const coordinates = readCoordinates(
            "weatherLatitude",
            "weatherLongitude"
        );

        state.weatherCoordinates = coordinates;

        const params = queryString(coordinates);

        const [currentResult, latestResult] =
            await Promise.allSettled([
                apiRequest(`${API.weatherCurrent}?${params}`),
                apiRequest(`${API.weatherLatest}?${params}`)
            ]);

        if (
            currentResult.status === "fulfilled" &&
            currentResult.value.status === "success"
        ) {
            renderWeatherObject(
                $("weatherCurrent"),
                currentResult.value.data
            );
        } else {
            $("weatherCurrent").textContent =
                currentResult.status === "rejected"
                    ? currentResult.reason.message
                    : currentResult.value.message ||
                      "Current weather unavailable.";
        }

        if (
            latestResult.status === "fulfilled" &&
            latestResult.value.status === "success"
        ) {
            renderWeatherObject(
                $("weatherLatest"),
                latestResult.value.data
            );
        } else {
            $("weatherLatest").textContent =
                latestResult.status === "rejected"
                    ? latestResult.reason.message
                    : latestResult.value.message ||
                      "No stored weather observation found.";
        }

        collectButton.disabled = false;
        state.loadedModules.add("weather");

    } catch (error) {
        state.weatherCoordinates = null;
        showError(error.message);

    } finally {
        button.disabled = false;
    }
}


// Loads historical weather for a date range.
async function loadWeatherHistory(event) {
    if (event) event.preventDefault();

    const body = $("weatherHistoryBody");

    renderTableMessage(
        body,
        "Loading weather history...",
        6
    );

    try {
        if (!state.weatherCoordinates) {
            throw new Error(
                "Load weather for coordinates before requesting history."
            );
        }

        const start = $("weatherStart").value;
        const end = $("weatherEnd").value;

        if (!start || !end || start > end) {
            throw new Error(
                "Choose a valid weather history date range."
            );
        }

        const params = queryString({
            ...state.weatherCoordinates,
            start_date: `${start}T00:00:00`,
            end_date: `${end}T23:59:59.999999`
        });

        const result = await apiRequest(
            `${API.weatherHistory}?${params}`
        );

        if (
            result.status !== "success" ||
            !Array.isArray(result.data)
        ) {
            throw new Error(
                "Invalid weather history response."
            );
        }

        body.replaceChildren();

        result.data.forEach(record => {
            const row = document.createElement("tr");

            row.appendChild(
                createCell(formatDate(record.recorded_at))
            );

            row.appendChild(
                createCell(formatNumber(record.temperature_c, " °C"))
            );

            row.appendChild(
                createCell(formatNumber(record.rainfall_mm, " mm"))
            );

            row.appendChild(
                createCell(formatNumber(record.wind_speed_kmh, " km/h"))
            );

            row.appendChild(createCell(record.weather_code));
            row.appendChild(createCell(record.source));

            body.appendChild(row);
        });

        if (!result.data.length) {
            renderTableMessage(
                body,
                "No weather records found for this date range.",
                6
            );
        }

    } catch (error) {
        renderTableMessage(
            body,
            error.message,
            6,
            "text-danger"
        );

        showError(error.message);
    }
}


