// Renders notifications using text nodes to avoid interpreting API content as HTML.
function renderNotifications(items) {
    const body = $("notificationTableBody");
    body.replaceChildren();

    if (!Array.isArray(items) || items.length === 0) {
        renderTableMessage(body, "No notifications found for this filter.", 7);
        return;
    }

    items.forEach(item => {
        const row = document.createElement("tr");
        row.appendChild(createCell(formatDate(item.created_at)));

        const content = document.createElement("td");
        const title = document.createElement("div");
        title.className = "fw-semibold";
        title.textContent = item.title || "Untitled notification";
        const message = document.createElement("div");
        message.className = "small text-muted description-cell";
        message.textContent = item.message || "";
        content.append(title, message);
        row.appendChild(content);

        row.appendChild(createCell(item.notification_type || "—"));
        row.appendChild(createCell(item.risk_level || "—"));
        row.appendChild(createCell(item.delivery_status || "—"));

        const statusCell = document.createElement("td");
        statusCell.appendChild(createStatusBadge(item.is_read ? "Read" : "Unread"));
        row.appendChild(statusCell);

        const actionCell = document.createElement("td");
        if (item.is_read) {
            actionCell.textContent = "—";
        } else {
            const button = document.createElement("button");
            button.type = "button";
            button.className = "btn btn-outline-primary btn-sm";
            button.textContent = "Mark read";
            button.dataset.notificationId = String(item.id);
            button.addEventListener("click", () => markNotificationRead(item.id, button));
            actionCell.appendChild(button);
        }
        row.appendChild(actionCell);
        body.appendChild(row);
    });
}


// Retrieves one page of notifications belonging to the current administrator.
async function loadNotifications() {
    const requestNumber = ++state.notificationRequest;
    const errorBox = $("notificationListError");
    const body = $("notificationTableBody");
    errorBox.classList.add("d-none");
    renderTableMessage(body, "Loading notifications...", 7);

    const readStatus = $("notificationReadFilter").value;
    const params = new URLSearchParams({
        page: String(state.notificationPage),
        per_page: String(state.notificationPerPage)
    });
    if (readStatus !== "") params.set("is_read", readStatus);

    try {
        const result = await apiRequest(`${API.notifications}?${params.toString()}`);
        if (requestNumber !== state.notificationRequest) return;
        if (result.status !== "success" || !Array.isArray(result.notifications) || !result.pagination) {
            throw new Error("Invalid notifications response.");
        }

        renderNotifications(result.notifications);
        const pagination = result.pagination;
        state.notificationTotalPages = Number(pagination.total_pages) || 0;
        const total = Number(pagination.total) || 0;
        $("notificationSummary").textContent = `${total} notification${total === 1 ? "" : "s"}`;
        $("notificationPaginationInfo").textContent = state.notificationTotalPages
            ? `Page ${pagination.page} of ${state.notificationTotalPages}`
            : "No pages";
        $("notificationPrevious").disabled = state.notificationPage <= 1;
        $("notificationNext").disabled = state.notificationPage >= state.notificationTotalPages;
    } catch (error) {
        if (requestNumber !== state.notificationRequest) return;
        errorBox.textContent = error.message || "Unable to load notifications.";
        errorBox.classList.remove("d-none");
        renderTableMessage(body, "Notifications could not be loaded.", 7);
        $("notificationSummary").textContent = "";
        $("notificationPaginationInfo").textContent = "";
        $("notificationPrevious").disabled = true;
        $("notificationNext").disabled = true;
    }
}


